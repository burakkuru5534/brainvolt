// Keeps the app's error texts in step with the backend registry
// (docs/api/errors.md: "mobile ARB keys error_<code>").
//
// Reads backend/internal/platform/apierror/{codes,messages_tr,messages_en}.go,
// rewrites the error_* entries of lib/core/l10n/arb/app_{tr,en}.arb (other
// keys untouched) and generates lib/core/network/error_messages.g.dart.
// Run from mobile/: `dart run tool/gen_error_l10n.dart` (part of `make gen`).
import 'dart:convert';
import 'dart:io';

const _registry = '../backend/internal/platform/apierror';

Map<String, String> _codes() {
  final src = File('$_registry/codes.go').readAsStringSync();
  final re = RegExp(r'\t(\w+)\s+Code = "([A-Z_]+)"');
  return {for (final m in re.allMatches(src)) m.group(1)!: m.group(2)!};
}

Map<String, String> _messages(String file, Map<String, String> codes) {
  final src = File('$_registry/$file').readAsStringSync();
  final re = RegExp(r'\t(\w+):\s+"((?:[^"\\]|\\.)*)",');
  return {
    for (final m in re.allMatches(src))
      if (codes.containsKey(m.group(1)))
        codes[m.group(1)]!: jsonDecode('"${m.group(2)}"') as String,
  };
}

void _writeArb(
  String path,
  Map<String, String> messages, {
  required bool template,
}) {
  final file = File(path);
  final arb = (jsonDecode(file.readAsStringSync()) as Map<String, dynamic>)
    ..removeWhere((k, _) => k.startsWith('error_') || k.startsWith('@error_'));
  for (final code in messages.keys.toList()..sort()) {
    arb['error_$code'] = messages[code];
    if (template) {
      arb['@error_$code'] = {
        'description': 'Server error code $code (docs/api/errors.md).',
      };
    }
  }
  file.writeAsStringSync(
    '${const JsonEncoder.withIndent('  ').convert(arb)}\n',
  );
}

void main() {
  final codes = _codes();
  final tr = _messages('messages_tr.go', codes);
  final en = _messages('messages_en.go', codes);
  final all = codes.values.toSet();
  if (tr.keys.toSet().length != all.length ||
      en.keys.toSet().length != all.length) {
    stderr.writeln(
      'backend messages incomplete: ${all.length} codes, ${tr.length} TR, ${en.length} EN',
    );
    exit(1);
  }
  _writeArb('lib/core/l10n/arb/app_tr.arb', tr, template: true);
  _writeArb('lib/core/l10n/arb/app_en.arb', en, template: false);

  final sorted = all.toList()..sort();
  final out = StringBuffer()
    ..writeln(
      '// GENERATED by tool/gen_error_l10n.dart from the backend error registry.',
    )
    ..writeln('// Do not edit; run `make gen`.')
    ..writeln()
    ..writeln("import '../l10n/l10n.dart';")
    ..writeln()
    ..writeln('/// Every server error code of docs/api/errors.md.')
    ..writeln('const serverErrorCodes = <String>{')
    ..writeAll(sorted.map((c) => "  '$c',\n"))
    ..writeln('};')
    ..writeln()
    ..writeln(
      '/// The localized text of a server error code, or null if unknown.',
    )
    ..writeln(
      'String? serverErrorMessage(AppLocalizations l, String code) => switch (code) {',
    )
    ..writeAll(sorted.map((c) => "  '$c' => l.error_$c,\n"))
    ..writeln('  _ => null,')
    ..writeln('};');
  File('lib/core/network/error_messages.g.dart')
      .writeAsStringSync(out.toString());
  stdout.writeln('error texts: ${sorted.length} codes');
}
