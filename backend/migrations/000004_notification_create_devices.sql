-- notification.devices (docs/domain/schema-identity.md §4); the rest of the
-- notification schema arrives in Phase 9.
-- +goose Up
CREATE SCHEMA notification;

CREATE TABLE notification.devices (
  id               uuid        PRIMARY KEY,
  user_id          uuid        NOT NULL REFERENCES identity.users(id) ON DELETE CASCADE,
  installation_id  text        NOT NULL,          -- random UUID generated by the app on first launch
  platform         text        NOT NULL CHECK (platform IN ('android','ios')),
  fcm_token        text        UNIQUE,            -- NULL until push permission granted
  app_version      text        NOT NULL,
  locale           text        NOT NULL CHECK (locale IN ('tr','en')),
  last_seen_at     timestamptz NOT NULL,
  created_at       timestamptz NOT NULL,
  revoked_at       timestamptz,
  UNIQUE (installation_id)
);
CREATE INDEX devices_user_idx ON notification.devices (user_id) WHERE revoked_at IS NULL;

-- +goose Down
DROP SCHEMA notification CASCADE;
